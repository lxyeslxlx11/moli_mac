import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { GAME_PATCH_LIMITS, GamePatchError, parseGamePatchManifest, applyGamePatchCandidates,
  decodeGamePatchArchive, decodeLauncherUpdatePackage, LauncherUpdateError } from '../index.mjs';

const vectors = JSON.parse(readFileSync(new URL('../../analysis/launcher-v26/original-patch-vectors.json', import.meta.url)));
const fromHex = hex => Uint8Array.from(Buffer.from(hex, 'hex'));
const hex = bytes => Buffer.from(bytes).toString('hex');
const text = value => Uint8Array.from(Buffer.from(value, 'latin1'));
const get = name => vectors.scenarios.find(row => row.name === name);
const input = name => { const row = get(name); return { manifestBytes: fromHex(row.manifest_hex),
  files: row.files.map(file => ({ path: file.path, bytes: fromHex(file.hex) })),
  archives: row.archives.map(file => ({ blockOrdinal: file.blockOrdinal, bytes: fromHex(file.hex) })) }; };
const code = (action, expected) => assert.throws(action, error => error instanceof GamePatchError && error.code === expected);

test('31 independently generated byte grammar vectors preserve split/removal, first duplicate and raw fields', () => {
  for (const row of vectors.grammar) {
    const result = parseGamePatchManifest(fromHex(row.manifest_hex));
    assert.deepEqual({ blockCount: result.blockCount, skippedBlocks: result.skippedBlocks, operations: result.operations.map(op => ({
      ...op, fields: op.fields.map(field => ({ key_hex: hex(field.keyBytes), value_hex: hex(field.valueBytes) })) })) }, row.expected, row.name);
    assert.equal(result.trust, 'unverified'); assert.ok(Object.isFrozen(result.operations));
  }
});

test('10 Python zipfile/hashlib scenarios yield exact final files for create, append, replaceto and sequential operations', () => {
  for (const row of vectors.scenarios) {
    const result = applyGamePatchCandidates(input(row.name));
    assert.deepEqual(result.files.map(file => ({ path: file.path, hex: hex(file.bytes),
      md5: createHash('md5').update(file.bytes).digest('hex') })), row.expected_files, row.name);
    assert.equal(result.trust, 'unverified'); assert.equal(result.authentication, 'unverified'); assert.equal(result.replacement, 'not-performed');
  }
});

test('game archives decode all central entries and permit a leading directory; self-updater still selects a first regular entry', () => {
  const result = decodeGamePatchArchive(input('directory-first').archives[0].bytes);
  assert.equal(result.entries.length, 3); assert.equal(result.entries[0].entry.directory, true);
  assert.equal(result.entries[0].payloadBytes.length, 0); assert.equal(result.crcVerified, true);
  assert.throws(() => decodeLauncherUpdatePackage(input('directory-first').archives[0].bytes, { expectedMd5: '0'.repeat(32) }), error => error instanceof LauncherUpdateError && error.code === 'ZIP_ENTRY_TYPE');
});

test('every archive entry has CRC checked, including a non-target second entry', () => {
  const archive = fromHex(vectors.malicious_archives['second-crc']), decoded = decodeGamePatchArchive(archive);
  const second = decoded.entries[1].entry; archive[second.dataOffset] ^= 1;
  assert.throws(() => decodeGamePatchArchive(archive), error => error instanceof LauncherUpdateError && ['ZIP_CRC_MISMATCH', 'ZIP_DEFLATE'].includes(error.code));
});

test('archive traversal, absolute and drive paths, reserved names, aliases and file/directory conflicts are rejected', () => {
  for (const name of ['traversal','absolute','drive','case-alias','file-directory','reserved','directory-file-prefix']) {
    const value = input('create-deflate'); value.archives[0].bytes = fromHex(vectors.malicious_archives[name]);
    assert.throws(() => applyGamePatchCandidates(value), error => error instanceof GamePatchError && ['PATCH_PATH', 'PATCH_PATH_ALIAS'].includes(error.code), name);
  }
});

test('nonempty directory payloads are rejected before path application', () => {
  assert.throws(() => decodeGamePatchArchive(fromHex(vectors.malicious_archives['empty-directory-body'])), error => error instanceof LauncherUpdateError && error.code === 'ZIP_ENTRY_TYPE');
});

test('failed final digest and later missing archive leave all caller data unchanged', () => {
  for (const name of ['create-deflate', 'sequential-create-append']) {
    const value = input(name), original = structuredClone(value);
    if (name.startsWith('create')) value.manifestBytes = text(Buffer.from(value.manifestBytes).toString('latin1').replace(/md5:[0-9a-f]{32}/, 'md5:'+'0'.repeat(32)));
    else value.archives.pop();
    const before = structuredClone(value);
    code(() => applyGamePatchCandidates(value), name.startsWith('create') ? 'PATCH_DIGEST_MISMATCH' : 'PATCH_ARCHIVE_MISSING');
    assert.deepEqual(value, before); assert.deepEqual(value.files, original.files);
  }
});

test('output file and manifest field bytes are owned and cannot mutate caller inputs or a subsequent result', () => {
  const value = input('replaceto-deflate'), original = structuredClone(value), result = applyGamePatchCandidates(value);
  result.files[0].bytes.fill(7); result.manifest.operations[0].fields[0].valueBytes.fill(8);
  assert.deepEqual(value, original); assert.deepEqual(applyGamePatchCandidates(value).files.map(file => hex(file.bytes)), get('replaceto-deflate').expected_files.map(file => file.hex));
  assert.ok(Object.isFrozen(result) && Object.isFrozen(result.files) && Object.isFrozen(result.operations));
});

test('append uses old bytes plus the named ZIP chunk, and does not promote other staging entries', () => {
  const value = applyGamePatchCandidates(input('append-deflate'));
  assert.equal(value.files.length, 1); assert.equal(value.files[0].path, 'Bin/new.bin');
  assert.equal(value.operations[0].removedPath, 'Bin/old.bin'); assert.equal(value.operations[0].md5Verified, true);
});

test('already-current and missing-base operations need no archive, and explicit unused archives fail', () => {
  assert.equal(applyGamePatchCandidates(input('already-current')).operations[0].disposition, 'current');
  assert.equal(applyGamePatchCandidates(input('append-base-missing')).operations[0].disposition, 'skipped-base-missing');
  const value = input('already-current'); value.archives = input('create-deflate').archives;
  code(() => applyGamePatchCandidates(value), 'PATCH_ARCHIVE_UNUSED');
});

test('append never overwrites an existing distinct rename destination', () => {
  const value = input('append-deflate'); value.files.push({ path: 'Bin/new.bin', bytes: text('existing') });
  code(() => applyGamePatchCandidates(value), 'PATCH_PATH_ALIAS');
});

test('replacement same-path aliases are rejected and strict MD5 policy is separate from native parsing', () => {
  const value = input('replaceto-deflate'); value.manifestBytes = text(Buffer.from(value.manifestBytes).toString('latin1').replace('old_name:old.bin','old_name:NEW.BIN'));
  code(() => applyGamePatchCandidates(value), 'PATCH_PATH_ALIAS');
  for (const replacement of ['md5:no-digest', 'md5:'+'A'.repeat(32), 'unused:value']) {
    const append = input('append-deflate'); append.manifestBytes = text(Buffer.from(append.manifestBytes).toString('latin1').replace(/md5:[0-9a-f]{32}/, replacement));
    assert.equal(parseGamePatchManifest(append.manifestBytes).operations.length, 1);
    code(() => applyGamePatchCandidates(append), 'PATCH_DIGEST_POLICY');
  }
});

test('manifest path validation rejects traversal and unsupported encoding while the parser preserves opaque high bytes', () => {
  for (const name of ['../x.bin','/x.bin','a//b.bin','a/./b.bin','bad.bin.','\xd6\xd0.bin']) {
    const value = input('create-deflate'); value.manifestBytes = text(Buffer.from(value.manifestBytes).toString('latin1').replace('name:new.bin','name:'+name));
    assert.equal(parseGamePatchManifest(value.manifestBytes).operations.length, 1); code(() => applyGamePatchCandidates(value), 'PATCH_PATH');
  }
  const drive = input('create-deflate'); drive.manifestBytes = text(Buffer.from(drive.manifestBytes).toString('latin1').replace('name:new.bin','name:C:x.bin'));
  drive.archives = []; assert.equal(applyGamePatchCandidates(drive).operations[0].disposition, 'skipped-missing-fields');
});

test('input files reject duplicate, case alias and ancestor shadowing paths', () => {
  for (const paths of [['a','a'],['a','A'],['a','A/child']]) {
    code(() => applyGamePatchCandidates({ manifestBytes: text(''), files: paths.map(path => ({ path, bytes: text('x') })), archives: [] }), 'PATCH_PATH_ALIAS');
  }
});

test('archive inputs must uniquely name actual blocks and all required blocks must be supplied', () => {
  const value = input('create-deflate'); value.archives.push(value.archives[0]); code(() => applyGamePatchCandidates(value), 'PATCH_ARCHIVE_INPUT');
  for (const blockOrdinal of [-1,1,0.5,'0']) { const value = input('create-deflate'); value.archives[0].blockOrdinal = blockOrdinal; code(() => applyGamePatchCandidates(value), 'PATCH_ARCHIVE_INPUT'); }
  const missing = input('create-deflate'); missing.archives=[]; code(() => applyGamePatchCandidates(missing), 'PATCH_ARCHIVE_MISSING');
});

test('append requires its named chunk and create requires a final matching destination', () => {
  for (const name of ['append-deflate','create-deflate']) {
    const value = input(name); value.manifestBytes = text(Buffer.from(value.manifestBytes).toString('latin1').replace('name:new.bin','name:absent.bin'));
    code(() => applyGamePatchCandidates(value), name.startsWith('append') ? 'PATCH_APPEND_CHUNK' : 'PATCH_DIGEST_MISMATCH');
  }
});

test('native missing metadata and unknown commands produce explicit skip reports without invented updates', () => {
  const result = applyGamePatchCandidates({ manifestBytes: text('unknown\nname:x}create\nname:x}append\nname:x}'), files: [], archives: [] });
  assert.equal(result.manifest.skippedBlocks.length, 1); assert.deepEqual(result.operations.map(op => op.disposition), ['skipped-missing-fields', 'skipped-missing-fields']);
  assert.deepEqual(result.files, []);
});

test('NUL truncation, manifest byte/field/line/block/operation budgets fail explicitly', () => {
  code(() => parseGamePatchManifest(text('create\0\nname:x}')), 'PATCH_NUL');
  for (const value of [new Uint8Array(GAME_PATCH_LIMITS.manifestBytes+1), text('create\nk:'+'x'.repeat(GAME_PATCH_LIMITS.fieldBytes+1)),
    text('create\n'+('k:x\n'.repeat(GAME_PATCH_LIMITS.linesPerBlock))), text('}'.repeat(GAME_PATCH_LIMITS.blocks+1)),
    text('create\nname:x}'.repeat(GAME_PATCH_LIMITS.operations+1))]) code(() => parseGamePatchManifest(value), 'PATCH_BUDGET');
});

test('actual typed-array lengths, offset buffers and own-data records resist metadata substitution', () => {
  class Wrong extends Uint8Array { get length() { return 0; } *[Symbol.iterator]() { yield 0; } }
  const source = text('create\nname:x}'); assert.equal(parseGamePatchManifest(new Wrong(source)).operations.length, 1);
  const padded = new Uint8Array(source.length+8); padded.set(source,4); assert.equal(parseGamePatchManifest(padded.subarray(4,-4)).operations.length,1);
  assert.equal(parseGamePatchManifest(source.buffer).operations.length,1);
  for (const value of [null,'data',[],new DataView(new ArrayBuffer(4)),new Proxy(source,{})]) code(() => parseGamePatchManifest(value), 'PATCH_INPUT');
  const value = input('create-stored'); Object.defineProperty(value, 'files', { get() { throw Error('must not read getter'); } }); code(() => applyGamePatchCandidates(value), 'PATCH_INPUT');
  const transferred = new Uint8Array(8); structuredClone(transferred.buffer, { transfer:[transferred.buffer] }); code(() => parseGamePatchManifest(transferred), 'PATCH_INPUT');
});

test('Windows separators normalize only within the strict memory-key profile', () => {
  const value = input('create-deflate'); value.manifestBytes = text(Buffer.from(value.manifestBytes).toString('latin1').replace('path:Bin','path:Data\\Bin'));
  assert.deepEqual(applyGamePatchCandidates(value).files.map(row => row.path), ['keep.txt','Data/Bin/new.bin','Data/Bin/extra.bin']);
});

test('file count, file byte and path length budgets are enforced before candidate work', () => {
  code(() => applyGamePatchCandidates({ manifestBytes: text(''), files: Array.from({ length: GAME_PATCH_LIMITS.files+1 }, (_, i) => ({ path: 'f'+i, bytes: text('') })), archives: [] }), 'PATCH_INPUT');
  code(() => applyGamePatchCandidates({ manifestBytes: text(''), files: [{ path:'large', bytes:new Uint8Array(GAME_PATCH_LIMITS.fileBytes+1) }], archives: [] }), 'PATCH_BUDGET');
  code(() => applyGamePatchCandidates({ manifestBytes: text(''), files: [{ path:'a'.repeat(GAME_PATCH_LIMITS.pathBytes+1), bytes:text('') }], archives: [] }), 'PATCH_PATH');
});
